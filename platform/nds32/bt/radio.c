#define N(t) (sizeof t / sizeof t[0])

/* the synthesizer's setting for f MHz: f / 9 in 16.16, and round(f * 4 / 9) */
static void lo_freq(unsigned mhz, uint16_t *n, uint16_t *frac, uint16_t *band)
{
    uint32_t q = (uint32_t)((((uint64_t)mhz << 16) + 4u) / 9u);   /* rounded: 2400 -> 0x010A.AAAB, 2401 -> 0x010A.C71C */
    *n = (uint16_t)(q >> 16); *frac = (uint16_t)q; *band = (uint16_t)((mhz * 4u + 4u) / 9u);
}

/* The oscillator: set-up, then a measurement at each of 96 frequencies (2400..2495 MHz) kept in registers 0x73..0x8A */
static int lo_init(void)
{
    uint8_t m[96];
    unsigned k;
    rf_clr(0x50, 3); rf_clr(0x51, 3);
    rf_wr(0x213, 0x1593); rf_wr(0x214, 0x0FAE); rf_wr(0x215, 0x0059);
    rf_set(0x146, 0x01); rf_set(0x146, 0x04);
    rf_set(0x200, 0x20); rf_set(0x200, 0x04); rf_set(0x200, 0x02); rf_set(0x200, 0x80);
    rf_set(0x201, 0x01);
    for (k = 0; k < 96u; k++) {
        uint16_t n, frac, band;
        lo_freq(2400u + k, &n, &frac, &band);
        rf_wr(0x53, band); rf_wr(0x148, n); rf_wr(0x149, frac);
        rf_diag_step = k;
        if (rf_wait(0x55)) return -1;
        m[k] = (uint8_t)rf_rd(0x54);
        if ((k & 3u) == 3u) rf_wr(0x73u + k / 4u, (uint16_t)(m[k - 2u] | (m[k] << 8)));
    }
    rf_wr(0x70, 0x010A); rf_wr(0x71, 0xAAAB); rf_wr(0x72, 0x1C71);
    rf_wr(0x146, 0);
    return 0;
}

static int fd_init(void)
{
    rf_set(0x200, 0x1F); rf_set(0x204, 0x2000); rf_set(0x202, 0x04); rf_set(0x202, 0x08); rf_set(0x4D, 0x01);
    rf_clr(0x000, 0x04); rf_set(0x000, 0x04);
    if (rf_wait(0x02)) return -1;
    (void)rf_rd(0x4E); (void)rf_rd(0x4F);
    return 0;
}

static void work_init(void)
{
    unsigned k;
    for (k = 0; k < N(work); k++) rf_wr(work[k][0], work[k][1]);
    rf_set(0x1E, 0x20); rf_set(0x1E, 0x08);
    rf_set(0x498, 0x04);
    rf_clr(0x170, 0x01); rf_clr(0x15C, 0x03); rf_clr(0x498, 0x01); rf_clr(0x49A, 0x01);
    rf_wr(0x49A, (uint16_t)((rf_rd(0x49A) & ~0x7F00u) | 0x1700u));
    rf_wr(0x498, (uint16_t)((rf_rd(0x498) & ~0x01F0u) | 0x0100u));
    rf_clr(0x39, 0x40);
}

static void digital_outputs(void)
{
    R16(0x4000C880u) = 0x8888; R16(0x4000C884u) = 0x8888; R16(0x4000C888u) = 0x0088;
    rf_wr(0x32, 0x001B);
    R16(0x4000C898u) = 0x018C;
}

/* ---- Calibration (MxdRfInit with no saved values: DCOC, LO leakage, TX IQ imbalance, LO leakage again) ---- */

/* waits until (register n & mask) is set; 0, or -1 after a time-out */
static int rf_until(unsigned n, uint16_t mask)
{
    uint32_t k;
    for (k = 0; k < 400000u; k++) if (rf_rd(n) & mask) return 0;
    return -1;
}

