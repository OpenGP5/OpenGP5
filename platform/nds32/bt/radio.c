static void table(const uint16_t (*t)[2], unsigned n) { unsigned k; for (k = 0; k < n; k++) rf_wr(t[k][0], t[k][1]); }

/* tunes to mhz (bcrux2SetFreqMhzBt): 0, or -1 if the synthesizer doesn't lock */
static int set_freq(unsigned mhz)
{
    rf_set(0x200, 0x20); rf_set(0x200, 0x04); rf_set(0x200, 0x02); rf_clr(0x200, 0x80);
    rf_set(0x201, 0x01);
    if (mhz - 2400u >= 0x60u && mhz >= 0x60u) return -1;
    rf_wr(0x147, (uint16_t)((rf_rd(0x147) & ~0x7Fu) | mhz));     /* as the library does it: the whole value OR'd in */
    if (rf_until(0x55, 1)) return -1;
    return (rf_rd(0x55) & 1u) ? 0 : -1;
}

/* one automatic DC-offset measurement */
static int dcoc_run(void)
{
    int r;
    rf_set(0x15A, 0x02);
    r = rf_until(0x159, 0x08);
    rf_clr(0x15A, 0x02);
    return r;
}

static int cal_dcoc(void)                                       /* receive DC offset */
{
    table(host_rx, N(host_rx));
    (void)set_freq(2400);
    rf_clr(0x152, 0x02);
    rf_clr(0x204, 0x04); rf_clr(0x204, 0x08);
    rf_wr(0x49A, 0); rf_wr(0x32, 0x0B); rf_wr(0x152, 0x0478); rf_wr(0x15B, 0); rf_wr(0x15C, 2);
    if (dcoc_run()) return -1;
    rf_clr(0x15C, 0x02);
    rf_set(0x204, 0x04); rf_set(0x204, 0x08);
    rf_wr(0x49A, 0); rf_wr(0x15F, 0x0B); rf_wr(0x32, 0x0B); rf_wr(0x152, 0x0478); rf_wr(0x15B, 0); rf_wr(0x15C, 1);
    if (dcoc_run()) return -1;
    rf_clr(0x15C, 0x01);
    rf_set(0x152, 0x02);
    return 0;
}

static void tx_tone(void)                                       /* a test tone for the transmit calibrations */
{
    rf_wr(0x20, 0x0013); rf_wr(0x21, 0xB13B); rf_wr(0x22, 0x0013); rf_wr(0x23, 0xB13B);
    rf_wr(0x1F, 0x0038);
    rf_set(0x1E, 0x80);
}

static int cal_loft(void)                                       /* LO leakage (carrier) */
{
    uint16_t v;
    table(host_tx, N(host_tx));
    (void)set_freq(2450);
    tx_tone();
    rf_set(0x175, 0x07); rf_wr(0x175, (uint16_t)((rf_rd(0x175) & ~0x18u) | 0x10u));
    rf_wr(0x173, 0x0FE2); rf_wr(0x174, 0x01EE);
    rf_clr(0x498, 0x01);
    rf_set(0x170, 0x07);
    rf_wr(0x176, (uint16_t)((rf_rd(0x176) & ~0x60u) | 0x20u));
    rf_wr(0x177, (uint16_t)((rf_rd(0x177) & ~0xFC0u) | 0x7C0u));
    rf_wr(0x177, (uint16_t)((rf_rd(0x177) & ~0x3Fu) | 0x1Fu));
    rf_wr(0x172, 0x105F);
    rf_wr(0x176, (uint16_t)((rf_rd(0x176) & ~0x1Fu) | 0x17u));
    rf_set(0x171, 0x01);
    if (rf_until(0x17B, 1)) return -1;
    if (!(rf_rd(0x17B) & 1u)) return -1;
    v = rf_rd(0x178);
    (void)rf_rd(0x179); (void)rf_rd(0x17A); (void)rf_rd(0x17C);
    v = (uint16_t)((v << 8) | (v >> 8));                        /* bytes swapped */
    rf_wr(0x430, v); rf_wr(0x433, v); rf_wr(0x436, v); rf_wr(0x439, v);
    return 0;
}

static int iq_measure(uint32_t *avg)                            /* five readings of register 0x19, averaged */
{
    uint32_t k, sum = 0;
    for (k = 0; k < 5u; k++) {
        rf_set(0x15, 0x01);
        if (rf_until(0x02, 0x02)) return -1;
        sum += rf_rd(0x19);
    }
    *avg = sum / 5u;
    return 0;
}

static int cal_tximb(void)                                      /* TX IQ imbalance: gain, then phase */
{
    uint32_t k, v, best;
    uint16_t pick;
    table(host_tx, N(host_tx));
    (void)set_freq(2450);
    tx_tone();
    rf_wr(0x17, 0x0F89); rf_wr(0x18, 0x03D4); rf_wr(0x39, 0x004A);
    rf_set(0x1E, 0x08); rf_set(0x16, 0x20); rf_clr(0x32, 0x08); rf_clr(0x170, 0x01);
    rf_set(0x498, 0x04); rf_wr(0x498, (uint16_t)((rf_rd(0x498) & ~0x1F0u) | 0x170u));
    rf_wr(0x1F, 0x0038);
    rf_wr(0x26, 0); rf_wr(0x25, 0x200); rf_wr(0x27, 0x200); rf_wr(0x26, 0);
    best = 0xFFFF; pick = iq_gain[0];
    for (k = 0; k < 21u; k++) {
        rf_wr(0x25, iq_gain[k]);
        rf_set(0x15, 0x01);
        if (rf_until(0x02, 0x02)) return -1;
        if (iq_measure(&v)) return -1;
        if (v < best) { best = v; pick = iq_gain[k]; }
    }
    rf_wr(0x25, pick);
    best = 0xFFFF; pick = iq_phase[0];
    for (k = 0; k < 86u; k++) {
        uint32_t i, sum = 0;
        rf_wr(0x26, iq_phase[k]);
        rf_set(0x15, 0x01);
        if (rf_until(0x02, 0x02)) return -1;
        for (i = 0; i < 5u; i++) {
            sum += rf_rd(0x19);
            rf_set(0x15, 0x01);
            if (rf_until(0x02, 0x02)) return -1;
        }
        if (sum / 5u < best) { best = sum / 5u; pick = iq_phase[k]; }
    }
    rf_wr(0x26, pick);
    return 0;
}

/* MxdRfInit: 0 or a negative step number */
int radio_start(void)
{
    unsigned k;
    rf_wr(0x05, 1);
    rf_wr(0x00, 0); rf_wr(0x00, 0xFFFF);                        /* common set-up */
    for (k = 0; k < N(rx_gain); k++) rf_wr(rx_gain[k][0], rx_gain[k][1]);
    for (k = 0; k < N(tx_gain); k++) rf_wr(tx_gain[k][0], tx_gain[k][1]);
    if (lo_init()) return -1;
    rf_wr(0x2D, 0x0200);
    rf_clr(0x200, 0x80); rf_set(0x201, 0x01);
    if (fd_init()) return -2;
    if (cal_dcoc()) return -3;
    if (cal_loft()) return -4;
    if (cal_tximb()) return -5;
    if (cal_loft()) return -6;
    work_init();
    digital_outputs();
    rf_set(0x200, 0x7F);                                         /* Bluetooth mode */
    return 0;
}
