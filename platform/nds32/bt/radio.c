/* The Bluetooth radio's start-up on the control processor (BP1048: MaxScend radio behind a RivieraWaves BT/BLE core).
 * Our own code. The register addresses, bits, values and the order of the steps were read from MVsilicon's SDK
 * library (rf_init, MxdRfInit and the functions it calls; work/bluetooth/notes.md); nothing of it is copied or linked.
 *
 * With the radio's self-calibration (receive DC offset, carrier leakage, transmit IQ balance), measured at every
 * start: the library can also load saved values instead (MxdRfSetClbrPara); we always measure. */
#include <stdint.h>
#include "radio.h"

#define R32(a) (*(volatile uint32_t *)(a))
#define R16(a) (*(volatile uint16_t *)(a))

/* Radio registers: written at RF_BASE + 4 * n (16 bits). Registers 0x800..0x8FF are read through a window:
 * index to 0x4000A044, 1 to 0x4000A040, the value from 0x4000A048 (below 0x818) or 0x4000A04C. */
#define RF_BASE 0x40009000u
#define RF_WIN  0x4000A040u

void rf_wr(unsigned n, uint16_t v) { R16(RF_BASE + 4u * n) = v; }

uint16_t rf_rd(unsigned n)
{
    if (n - 0x800u >= 0x100u) return R16(RF_BASE + 4u * n);    /* unsigned, as the library's slti: only 0x800..0x8FF
                                                                  * go through the window (found 2026-11-22 on the pedal) */
    R16(RF_WIN + 0x4u) = (uint16_t)n;
    R16(RF_WIN) = 1;
    return n < 0x818u ? R16(RF_WIN + 0x8u) : R16(RF_WIN + 0xCu);
}

static void rf_set(unsigned n, uint16_t bits) { rf_wr(n, rf_rd(n) | bits); }
static void rf_clr(unsigned n, uint16_t bits) { rf_wr(n, rf_rd(n) & (uint16_t)~bits); }

/* waits for bit 0 of register n; 0 when it came (and stayed), -1 on a time-out */
uint32_t rf_diag_step, rf_diag_val;   /* the oscillator step that failed, the last value of its "done" register */

static int rf_wait(unsigned n)
{
    uint32_t k;
    for (k = 0; k < 200000u; k++) if ((rf_diag_val = rf_rd(n)) & 1u) return (rf_rd(n) & 1u) ? 0 : -1;
    return -1;
}

