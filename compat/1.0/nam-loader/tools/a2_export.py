#!/usr/bin/env python3
"""Export a NAM A2 Lite WaveNet (.nam) to a C header for the a2_lite streaming kernel.

Accepts a Valeton-style SlimmableContainer (picks the width-3 submodel by default, or
--width N) or a plain WaveNet .nam. Only the A2 Lite topology is accepted:
  one layer array, input_size 1, condition_size 1, LeakyReLU (no gating), layer1x1 active,
  head1x1 inactive, bottleneck == channels, groups 1, no FiLM, head_rechannel out_channels 1,
  top-level head None.
The weights are emitted VERBATIM in NAM's flat import order, so on-device model storage is just
the .nam weight list; a2_lite_init() walks it using the per-layer kernel sizes/dilations.

Flat order (nam/models/wavenet import_weights):
  rechannel.w[C]                             (Conv1d 1->C, k=1, no bias)
  per layer: conv.w[C][C][K], conv.b[C], mixer.w[C] (1->C, no bias), l1x1.w[C][C], l1x1.b[C]
  head_rechannel.w[1][C][KH], head_rechannel.b[1]
  head_scale

  a2_export.py model.nam out.h [--width 3] [--name a2_model]
Stdlib only.
"""
import argparse, json, math, struct
from pathlib import Path


def f32(v):
    y = struct.unpack('<f', struct.pack('<f', float(v)))[0]
    if not math.isfinite(y):
        raise ValueError('non-finite weight')
    return y


def pick_wavenet(d, width):
    if d.get('architecture') == 'SlimmableContainer':
        subs = [s['model'] for s in d['config']['submodels']]
        ws = {s['config']['layers'][0]['channels']: s for s in subs}
        if width not in ws:
            raise ValueError(f'no width-{width} submodel (have {sorted(ws)})')
        return ws[width]
    if d.get('architecture') != 'WaveNet':
        raise ValueError(f'unsupported architecture {d.get("architecture")}')
    return d


def check_a2(m):
    cfg = m['config']
    if cfg.get('head') is not None:
        raise ValueError('top-level head unsupported')
    if len(cfg['layers']) != 1:
        raise ValueError('A2 Lite has exactly one layer array')
    L = cfg['layers'][0]
    C = L['channels']
    nl = len(L['dilations'])
    ks = L.get('kernel_sizes') or ([L['kernel_size']] * nl if isinstance(L.get('kernel_size'), int) else L['kernel_size'])
    acts = L['activation'] if isinstance(L['activation'], list) else [L['activation']] * nl
    gm = L.get('gating_mode', ['none'] * nl)
    gm = gm if isinstance(gm, list) else [gm] * nl
    ok = (L['input_size'] == 1 and L['condition_size'] == 1 and L.get('bottleneck', C) == C
          and L['head']['out_channels'] == 1 and L['head'].get('bias', True)
          and L['layer1x1']['active'] and L['layer1x1'].get('groups', 1) == 1
          and not L['head1x1']['active'] and L.get('groups_input', 1) == 1
          and L.get('groups_input_mixin', 1) == 1 and len(ks) == nl
          and all(g == 'none' for g in gm)
          and all(a.get('type') == 'LeakyReLU' for a in acts)
          and not any(v.get('active') for k, v in L.items() if k.endswith('_film') and isinstance(v, dict)))
    if not ok:
        raise ValueError('not an A2 Lite topology (see docstring)')
    slopes = {a.get('negative_slope', 0.01) for a in acts}
    if len(slopes) != 1:
        raise ValueError('mixed LeakyReLU slopes unsupported')
    KH = L['head']['kernel_size']
    n = C + sum(C * C * k + C + C + C * C + C for k in ks) + C * KH + 1 + 1
    w = [f32(v) for v in m['weights']]
    if len(w) != n:
        raise ValueError(f'expected {n} weights, got {len(w)}')
    if abs(w[-1] - cfg.get('head_scale', w[-1])) > 1e-5:
        raise ValueError('head_scale in weights disagrees with config')
    if m.get('sample_rate', 48000) not in (48000, 48000.0):
        raise ValueError('model must be 48 kHz')
    return dict(C=C, NL=nl, K=ks, D=L['dilations'], KH=KH, slope=slopes.pop(), w=w)


def emit(a, name):
    def cf(v):
        s = '%.9g' % v
        return (s if any(c in s for c in '.eEn') else s + '.0') + 'f'
    ring = sum((k - 1) * d + 1 for k, d in zip(a['K'], a['D'])) * a['C']
    o = [f'/* Generated by tools/a2_export.py. NAM A2 Lite, weights in NAM flat order. */',
         f'#define {name.upper()}_C {a["C"]}', f'#define {name.upper()}_NL {a["NL"]}',
         f'#define {name.upper()}_KH {a["KH"]}', f'#define {name.upper()}_NW {len(a["w"])}',
         f'#define {name.upper()}_RING_FLOATS {ring}  /* sum((K-1)*D+1)*C */',
         f'static const unsigned char {name}_K[] = {{ {", ".join(map(str, a["K"]))} }};',
         f'static const unsigned short {name}_D[] = {{ {", ".join(map(str, a["D"]))} }};',
         f'static const float {name}_slope = {cf(a["slope"])};',
         f'static const float {name}_w[] = {{']
    for i in range(0, len(a['w']), 8):
        o.append('  ' + ', '.join(cf(v) for v in a['w'][i:i + 8]) + ',')
    o.append('};')
    return '\n'.join(o) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('model'); p.add_argument('out')
    p.add_argument('--width', type=int, default=3)
    p.add_argument('--name', default='a2_model')
    a = p.parse_args()
    try:
        m = check_a2(pick_wavenet(json.loads(Path(a.model).read_text()), a.width))
    except (ValueError, KeyError, TypeError) as e:
        p.error(str(e))
    Path(a.out).write_text(emit(m, a.name))
    print(f'wrote {a.out}: C={m["C"]} layers={m["NL"]} weights={len(m["w"])} '
          f'ring={sum((k-1)*d+1 for k, d in zip(m["K"], m["D"]))*m["C"]} floats')


if __name__ == '__main__':
    main()
