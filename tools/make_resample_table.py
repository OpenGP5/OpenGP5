#!/usr/bin/env python3
"""The USB audio playback resampler's filter (platform/nds32/usb_resample.h): a windowed sinc, TAPS taps, PHASES + 1
rows (phase 0 .. 1 in steps of 1 / PHASES; the resampler interpolates between two rows), Q15, every row summing to
exactly 32768 (no level or DC change as the phase moves).   python3 tools/make_resample_table.py [--check]

The ratio is always within about 0.1 % of 1 (it only follows the computer's clock against the DSP's), so the filter
only has to interpolate between samples, not change the bandwidth: cutoff just under the Nyquist frequency."""
import math, sys
TAPS, PHASES, FC, BETA = 16, 64, 0.455, 9.0          # FC in cycles per sample (0.5 = Nyquist)

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / 2 / k) ** 2; s += t; k += 1
    return s

def kernel(t):                                       # t: distance in samples from the output point
    h = TAPS / 2
    if abs(t) >= h: return 0.0
    sinc = 1.0 if t == 0 else math.sin(2 * math.pi * FC * t) / (2 * math.pi * FC * t)
    return 2 * FC * sinc * i0(BETA * math.sqrt(1 - (t / h) ** 2)) / i0(BETA)

def rows():
    out = []
    for p in range(PHASES + 1):
        f = p / PHASES                               # output at input position n + f; taps x[n - 7 .. n + 8]
        h = [kernel(j - (TAPS // 2 - 1) - f) for j in range(TAPS)]
        s = sum(h); q = [round(32768 * v / s) for v in h]
        q[TAPS // 2 - 1 + (1 if f >= 0.5 else 0)] += 32768 - sum(q)   # the largest tap takes the rounding
        out.append(q)
    return out

def main():
    r = rows()
    if "--check" in sys.argv:
        import cmath
        for p in (0, PHASES // 4, PHASES // 2):
            for fhz in (1000, 10000, 15000, 18000, 20000):
                w = 2 * math.pi * fhz / 44100
                g = abs(sum(c / 32768 * cmath.exp(-1j * w * j) for j, c in enumerate(r[p])))
                print(f"phase {p:2d}/{PHASES}: {fhz:5d} Hz {20 * math.log10(g):+6.2f} dB")
        return
    print("/* generated by tools/make_resample_table.py (do not edit): the playback resampler's filter, windowed sinc,")
    print(f" * {TAPS} taps, {PHASES} + 1 phases, cutoff {FC} of the sample rate, Kaiser beta {BETA}, Q15, rows sum to 32768 */")
    print(f"#define RS_TAPS {TAPS}u\n#define RS_PHASES {PHASES}u\n#define RS_PHASE_BITS {PHASES.bit_length() - 1}u")
    print("/* const (flash): a copy in RAM measured no faster on the pedal (2026-11-23) and RAM is short */")
    print(f"static const int16_t rs_table[{PHASES + 1}][{TAPS}] = {{")
    for q in r: print("    {" + ", ".join(str(v) for v in q) + "},")
    print("};")

main()
