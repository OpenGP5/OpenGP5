#!/usr/bin/env python3
"""Make platform/nds32/font5x7.h, the platform's built-in pixel font, from petabyt's 5x7 font
(tools/fonts/petabyt-font.h, https://github.com/petabyt/font, MIT licence).

  python3 tools/fonts/make_font5x7.py

The eight printable ASCII characters that font does not have ($ & @ [ \\ ] ^ |) come from the table below.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/fonts/petabyt-font.h"
OUT = ROOT / "platform/nds32/font5x7.h"

EXTRA = {   # column bytes, bit 0 = top row
    '$': (0x24, 0x2A, 0x7F, 0x2A, 0x12), '&': (0x36, 0x49, 0x55, 0x22, 0x50), '@': (0x32, 0x49, 0x79, 0x41, 0x3E),
    '[': (0x00, 0x7F, 0x41, 0x41, 0x00), '\\': (0x02, 0x04, 0x08, 0x10, 0x20), ']': (0x00, 0x41, 0x41, 0x7F, 0x00),
    '^': (0x04, 0x02, 0x01, 0x02, 0x04), '|': (0x00, 0x00, 0x7F, 0x00, 0x00),
}

def main():
    s = SRC.read_text(encoding="latin-1")
    glyphs = {}
    for c, body in re.findall(r"\{\s*'((?:\\.|[^'\\]))'\s*,\s*\{((?:\s*\"[^\"]*\"\s*,?)+)\}\}", s):
        c = bytes(c, "latin-1").decode("unicode_escape")
        rows = re.findall(r'"([^"]*)"', body)
        if len(rows) == 7 and c not in glyphs:
            glyphs[c] = tuple(sum(1 << y for y in range(7) if rows[y][x] == '#') for x in range(5))
    glyphs.update({k: v for k, v in EXTRA.items() if k not in glyphs})
    glyphs.setdefault(' ', (0, 0, 0, 0, 0))
    rows = []
    for code in range(0x20, 0x7F):
        g = glyphs[chr(code)]
        rows.append("{%s}" % ",".join("0x%02X" % b for b in g))
    body = "\n".join("    " + ",".join(rows[i:i + 4]) + "," for i in range(0, len(rows), 4))
    OUT.write_text('''#ifndef GP5_FONT5X7_H
#define GP5_FONT5X7_H
#include <stdint.h>
/* The platform's built-in pixel font (gp5_text): 5x7 in a 6x8 cell, printable ASCII 0x20..0x7E, one byte per
 * column, bit 0 = top row. Generated by tools/fonts/make_font5x7.py: do not edit.
 * From petabyt's 5x7 font, https://github.com/petabyt/font:
 *   MIT License, Copyright (c) 2020 Petabyte. Permission is hereby granted, free of charge, to any person
 *   obtaining a copy of this software and associated documentation files (the "Software"), to deal in the
 *   Software without restriction, including without limitation the rights to use, copy, modify, merge, publish,
 *   distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is
 *   furnished to do so, subject to the following conditions: The above copyright notice and this permission
 *   notice shall be included in all copies or substantial portions of the Software. THE SOFTWARE IS PROVIDED
 *   "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF
 *   MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR
 *   COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT,
 *   TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN
 *   THE SOFTWARE.
 * $ & @ [ \\ ] ^ | are not in that font and were added here. */
#define GP5_FONT5X7_LAST 0x7E
static const uint8_t font[][5] = {
%s
};
#endif
''' % body)
    print(OUT, "written,", len(rows), "glyphs")

if __name__ == "__main__":
    main()
