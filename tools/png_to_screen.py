#!/usr/bin/env python3
"""Turn a 160x80 PNG into an image the control processor draws on the GP-5's screen.

  python3 tools/png_to_screen.py logo.png platform/nds32/boot_logo.h [--name boot_logo] [--preview out.png]

The pixels are converted to the panel's 16-bit colour format (5 bits blue, 6 green, 5 red, as the platform's
rgb() packs them) and run-length encoded: { count, colour } pairs, row-major, so a mostly flat logo stays
small. --preview writes back what the screen will show (useful to judge the 16-bit colour). No image library
needed: 8-bit RGB / RGBA / grey / palette PNGs, not interlaced.
"""
import argparse, struct, sys, zlib
from pathlib import Path

W, H = 160, 80


def read_png(path):
    data = Path(path).read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n": sys.exit(f"{path}: not a PNG")
    o, idat, plte, trns = 8, b"", None, None
    while o < len(data):
        n, t = struct.unpack(">I4s", data[o:o + 8]); d = data[o + 8:o + 8 + n]
        if t == b"IHDR": w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", d)
        elif t == b"PLTE": plte = d
        elif t == b"tRNS": trns = d
        elif t == b"IDAT": idat += d
        o += 12 + n
    if depth != 8 or interlace: sys.exit("only 8-bit, non-interlaced PNGs")
    ch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    raw, stride, out, prev = zlib.decompress(idat), w * ch, [], bytearray(w * ch)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - ch] if i >= ch else 0; b = prev[i]; c = prev[i - ch] if i >= ch else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        prev = line
        for x in range(w):
            px = line[x * ch:(x + 1) * ch]
            if ctype == 0: r = g = b_ = px[0]; al = 255
            elif ctype == 2: r, g, b_ = px; al = 255
            elif ctype == 3: r, g, b_ = plte[3 * px[0]:3 * px[0] + 3]; al = trns[px[0]] if trns and px[0] < len(trns) else 255
            elif ctype == 4: r = g = b_ = px[0]; al = px[1]
            else: r, g, b_, al = px
            out.append(tuple((v * al) // 255 for v in (r, g, b_)))      # transparent = black (the screen's background)
    return w, h, out


def write_png(path, w, h, pixels):
    raw = b"".join(b"\0" + bytes(v for p in pixels[y * w:(y + 1) * w] for v in p) for y in range(h))
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    Path(path).write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                           + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def panel(r, g, b):          # platform/nds32/main.c rgb(): the panel runs in BGR order
    return ((b >> 3) << 11) | ((g >> 2) << 5) | (r >> 3)


def unpanel(c):
    r, g, b = c & 31, (c >> 5) & 63, c >> 11
    return (r << 3 | r >> 2, g << 2 | g >> 4, b << 3 | b >> 2)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("png"); ap.add_argument("header")
    ap.add_argument("--name", default="boot_logo"); ap.add_argument("--preview")
    a = ap.parse_args()
    w, h, px = read_png(a.png)
    if (w, h) != (W, H): sys.exit(f"{a.png} is {w}x{h}; the screen is {W}x{H}")
    cols = [panel(*p) for p in px]
    runs = []
    for c in cols:
        if runs and runs[-1][1] == c and runs[-1][0] < 65535: runs[-1][0] += 1
        else: runs.append([1, c])
    body = ",\n".join("    " + ", ".join(f"{{{n}, 0x{c:04X}}}" for n, c in runs[i:i + 6]) for i in range(0, len(runs), 6))
    Path(a.header).write_text(
        f"/* GENERATED by tools/png_to_screen.py from {Path(a.png).name}: {W}x{H}, panel colour format,\n"
        f" * run-length encoded ({len(runs)} runs, {4 * len(runs)} bytes; raw would be {2 * W * H}). Do not edit. */\n"
        f"#include <stdint.h>\n"
        f"static const struct {{ uint16_t count, colour; }} {a.name}[{len(runs)}] = {{\n{body}\n}};\n"
        f"#define {a.name.upper()}_RUNS {len(runs)}u\n")
    print(f"{a.header}: {len(runs)} runs, {4 * len(runs)} bytes")
    if a.preview: write_png(a.preview, W, H, [unpanel(c) for c in cols]); print(f"preview: {a.preview}")


if __name__ == "__main__":
    main()
